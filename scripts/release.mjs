import { execFileSync } from 'node:child_process';
import { readFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
process.chdir(root);
const run = (file, args) => execFileSync(file, args, { stdio: 'inherit', cwd: root });
const capture = (file, args) => execFileSync(file, args, { encoding: 'utf8', cwd: root }).trim();
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
if (!/^\d+\.\d+\.\d+$/.test(pkg.version)) throw new Error('Expected stable semantic version');
const tag = 'v' + pkg.version;
const repo = 'OuyangLing1999/Dsh-scriptForGin';
const windowsGh = path.join(process.env.LOCALAPPDATA || '', 'Microsoft/WinGet/Packages/GitHub.cli_Microsoft.Winget.Source_8wekyb3d8bbwe/bin/gh.exe');
const gh = process.env.GH_BIN || (existsSync(windowsGh) ? windowsGh : 'gh');
run(process.execPath, ['scripts/build-client.mjs']);
run(process.execPath, ['--check', 'client.js']);
run(process.execPath, ['--test']);
if (process.argv.includes('--check')) {
  console.log('Release preflight passed for ' + tag + '; no commit or push performed.');
  process.exit(0);
}
const remote = capture('git', ['remote', 'get-url', 'origin']);
if (!remote.endsWith('/' + repo + '.git') && !remote.endsWith(':' + repo + '.git')) throw new Error('Unexpected origin: ' + remote);
if (capture('git', ['branch', '--show-current']) !== 'main') throw new Error('Release from main only');
run(gh, ['auth', 'status']);
run('git', ['add', '-A']);
const staged = capture('git', ['diff', '--cached', '--name-only']);
if (staged) run('git', ['commit', '-m', 'Release ' + tag + ': script tools updates']);
run('git', ['push', '-u', 'origin', 'main']);
const tags = capture('git', ['tag', '--list', tag]);
if (!tags) run('git', ['tag', tag]);
else if (capture('git', ['rev-list', '-n', '1', tag]) !== capture('git', ['rev-parse', 'HEAD'])) throw new Error('Tag already points to another commit');
run('git', ['push', 'origin', tag]);
mkdirSync('dist', { recursive: true });
const archive = path.join(root, 'dist', 'Dsh-scriptForGin-' + tag + '.zip');
run('git', ['archive', '--format=zip', '--prefix=Dsh-scriptForGin/', '--output=' + archive, tag]);
const releaseExists = (() => { try { capture(gh, ['release', 'view', tag, '--repo', repo]); return true; } catch { return false; } })();
if (releaseExists) run(gh, ['release', 'upload', tag, archive, '--repo', repo, '--clobber']);
else run(gh, ['release', 'create', tag, archive, '--repo', repo, '--verify-tag', '--title', '剧本工具 ' + tag, '--notes-file', 'RELEASE_NOTES.md']);
console.log('Published https://github.com/' + repo + '/releases/tag/' + tag);
